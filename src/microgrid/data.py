"""Synthetic, fully reproducible input data for a fictional island microgrid.

Nothing here is measured data. The profiles are generated from simple,
documented shapes plus seeded noise so that anyone can reproduce them:

* Load: about 150 households plus a harbour/shop load, with a night base, a
  morning peak and a larger evening peak.
* Solar: a summer clear-sky bell curve (sunrise ~05:30, sunset ~21:00) scaled by a
  daily cloudiness factor.
* Wind: a smooth random series around a daily mean capacity factor.

Three days with different weather are generated by default:
day 1 sunny and calm, day 2 windy with passing clouds, day 3 overcast.
"""
from __future__ import annotations

import numpy as np
import pandas as pd

HOURS_PER_DAY = 24


def household_load(hours: np.ndarray, rng: np.random.Generator, homes: int = 150) -> np.ndarray:
    """Aggregate demand in kW for ``homes`` households plus a small commercial load."""
    h = hours % 24
    per_home = (
        0.22                                                  # night base (fridges, standby)
        + 0.30 * np.exp(-0.5 * ((h - 7.5) / 1.3) ** 2)        # morning peak
        + 0.12 * np.exp(-0.5 * ((h - 13.0) / 2.5) ** 2)       # midday activity
        + 0.62 * np.exp(-0.5 * ((h - 19.5) / 1.8) ** 2)       # evening peak
    )
    commercial = 12.0 * ((h >= 8) & (h < 18))                # harbour, shop, school
    noise = rng.normal(1.0, 0.04, size=hours.shape)
    return homes * per_home * noise + commercial


def solar_profile(hours: np.ndarray, rng: np.random.Generator, kwp: float, clearness: list[float]) -> np.ndarray:
    """PV output in kW for a summer location; ``clearness`` is one factor (0-1) per day."""
    h = hours % 24
    shape = np.clip(np.sin(np.pi * (h - 5.5) / 15.5), 0, None) ** 1.3   # zero outside 05:30-21:00
    day = (hours // 24).astype(int)
    k = np.array(clearness)[day]
    clouds = np.clip(rng.normal(1.0, 0.25 * (1 - k), size=hours.shape), 0.2, 1.1)  # more noise on cloudy days
    return np.clip(kwp * 0.80 * k * shape * clouds, 0, 0.85 * kwp)


def wind_profile(hours: np.ndarray, rng: np.random.Generator, capacity_kw: float, mean_cf: list[float]) -> np.ndarray:
    """Wind output in kW: a smoothed AR(1) series around a daily mean capacity factor."""
    day = (hours // 24).astype(int)
    target = np.array(mean_cf)[day]
    x = np.zeros(len(hours))
    for i in range(1, len(hours)):
        x[i] = 0.85 * x[i - 1] + rng.normal(0, 0.10)
    cf = np.clip(target + x, 0.0, 0.95)
    return capacity_kw * cf


def island_profiles(
    days: int = 3,
    seed: int = 7,
    homes: int = 150,
    pv_kwp: float = 150.0,
    wind_kw: float = 100.0,
    clearness: list[float] | None = None,
    wind_cf: list[float] | None = None,
) -> pd.DataFrame:
    """Return an hourly table with columns load, wind, solar (all kW)."""
    rng = np.random.default_rng(seed)
    clearness = clearness or [0.95, 0.60, 0.25][:days]
    wind_cf = wind_cf or [0.12, 0.55, 0.30][:days]
    hours = np.arange(days * HOURS_PER_DAY)
    df = pd.DataFrame(
        {
            "load": household_load(hours, rng, homes),
            "wind": wind_profile(hours, rng, wind_kw, wind_cf),
            "solar": solar_profile(hours, rng, pv_kwp, clearness),
        },
        index=pd.Index(hours, name="hour"),
    )
    return df.round(2)
